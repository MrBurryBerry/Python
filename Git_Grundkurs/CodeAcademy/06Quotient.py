#Erstelle die Variable Cucumbers mit der Anzahl von 100 und eine Variable mit den Personen als 6
cucumbers = 100
num_people = 6

#Erstelle einen Variable, die das Ergebnis an gibt wie viele gurken eine Person bekommt
whole_cucumbers_per_person =  cucumbers // num_people
print(whole_cucumbers_per_person)
# Gib das Ergebbnis in Float aus in Python 2 war es anders
float_cucumbers_per_person = float(cucumbers) / num_people
print(float_cucumbers_per_person)